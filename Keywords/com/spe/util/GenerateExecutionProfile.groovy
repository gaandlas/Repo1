public class GenerateExecutionProfile  {

	@Keyword
	public static void createProfile() throws ParserConfigurationException, TransformerException {
		DocumentBuilderFactory docFactory = DocumentBuilderFactory.newInstance();
		DocumentBuilder docBuilder = docFactory.newDocumentBuilder();

		Document doc = docBuilder.newDocument();
		Element rootElement = doc.createElement("GlobalVariableEntities");
		doc.appendChild(rootElement);

		doc.createElement("staff");
		rootElement.appendChild(doc.createElement("staff"));

		try {
			FileOutputStream output =
					new FileOutputStream("c:\\test\\staff-dom.xml")
			writeXml(doc, output);
		} catch (IOException e) {
			e.printStackTrace();
		}
	}
	private static void writeXml(Document doc, OutputStream output) throws TransformerException {

		TransformerFactory transformerFactory = TransformerFactory.newInstance();
		Transformer transformer = transformerFactory.newTransformer();
		transformer.setOutputProperty(OutputKeys.INDENT, "yes");
		DOMSource source = new DOMSource(doc);
		StreamResult result = new StreamResult(output);

		transformer.transform(source, result);
	}
}
